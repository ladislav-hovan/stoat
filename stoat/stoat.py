### Class definition ###
class Stoat:
    ### Initialisation ###
    def __init__(
        self,
        panda_obj: Optional[Panda] = None,
    ) -> None:

        # TODO: Implement network methods other than PANDA (PUMA, DRAGON?)

        # Variables generated by the class
        self.expression = None
        self.avg_expression = None
        self.spatial = None

        # Get the complete PANDA network and expression matrix from panda_obj
        if panda_obj is not None:
            self.panda_network = panda_obj.panda_network
            if not hasattr(panda_obj, 'expression_matrix'):
                print ('The PANDA object does not contain the expression ' +
                       'matrix, expression data need to be provided ' +
                       'from a different source')
            else:
                self.expression = pd.DataFrame(panda_obj.expression_matrix).T
                self.expression.index = panda_obj.expression_samples
                self.expression.columns = panda_obj.genes
                self.avg_expression = self.expression.copy()
    

    def load_spatial_dataset(
        self,
        path: Path,
        **kwargs,
    ) -> None:

        try:
            print ('Trying to load data in Visium format...')
            self.spatial = visium(path, **kwargs)
        except Exception:
            print ('Trying to load data in Visium HD format...')
            self.spatial = visium_hd(path, **kwargs)